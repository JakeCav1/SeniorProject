"""Install the read-only dashboard system service; activation is explicit."""
import argparse
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = Path("/usr/local/lib/chomp-edr/dashboard")
BINARY = Path("/usr/local/lib/chomp-edr/chompedr")
UNIT = Path("/etc/systemd/system/chompedr-dashboard.service")
SPEC = importlib.util.spec_from_file_location("chomp_installer", Path(__file__).with_name("install-system-linux.py"))
BASE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(BASE)


def unit_text(port):
    if not 1024 <= port <= 65535:
        raise ValueError("Port must be 1024..65535")
    return f"""# Generated by install-dashboard-linux.py
[Unit]
Description=Chomp EDR local web dashboard
After=systemd-journald.service
StartLimitIntervalSec=0

[Service]
Type=simple
DynamicUser=yes
SupplementaryGroups=systemd-journal
ExecStart=/usr/bin/python3 {DESTINATION}/server.py --binary {BINARY} --port {port}
Restart=always
RestartSec=10s
KillMode=control-group
TimeoutStopSec=15s
UMask=0077
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=strict
ProtectHome=yes
RestrictAddressFamilies=AF_INET AF_UNIX
Environment=PYTHONDONTWRITEBYTECODE=1
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=multi-user.target
"""


def install(port=8765, replace=False, destdir=None):
    if sys.platform != "linux":
        raise ValueError("The dashboard service requires Linux with systemd")
    if destdir is None and os.geteuid() != 0:
        raise ValueError("Use sudo for installation, or --destdir for staging")
    generated = unit_text(port)
    if destdir is None:
        if not BINARY.is_file():
            raise ValueError("Install the updated system collector binary first")
        # Fail clearly when the old binary lacks the embedded-rule export command.
        probe = subprocess.run([str(BINARY), "export-rules"], capture_output=True,
                               text=True, timeout=10, check=True)
        inventory = json.loads(probe.stdout)
        if inventory.get("source") != "embedded":
            raise ValueError("Rebuild and reinstall Chomp from the dashboard branch first")
    stage = Path("/") if destdir is None else Path(destdir).absolute()
    sources = ["server.py", "web/index.html", "web/app.js", "web/style.css"]
    destinations = [(stage / DESTINATION.relative_to("/") / name,
                     (ROOT / "dashboard" / name).read_bytes(), 0o644) for name in sources]
    destinations.append((stage / UNIT.relative_to("/"), generated.encode(), 0o644))
    for path, _, _ in destinations:
        BASE.regular_destination(path, replace)
    # The temporary web identity must be able to traverse these root-owned directories.
    for relative in [DESTINATION.parent.relative_to("/"), DESTINATION.relative_to("/"),
                     DESTINATION.relative_to("/") / "web"]:
        directory = stage / relative
        directory.mkdir(parents=True, exist_ok=True)
        directory.chmod(0o755)
    for path, content, mode in destinations:
        BASE.atomic_write(path, content, mode)
    return [path for path, _, _ in destinations]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--replace", action="store_true", help="Replace files after stopping the dashboard")
    parser.add_argument("--destdir", type=Path, help="Stage files only; skip installed-binary check and activation")
    args = parser.parse_args()
    for path in install(args.port, args.replace, args.destdir):
        print(f"Installed {path}")
    if args.destdir is not None:
        print("Staged only; no services enabled or started.")
        return
    print("Dashboard installed. Activate with:")
    print("  sudo systemctl daemon-reload")
    print("  sudo systemctl enable --now chompedr-dashboard.service")
    print(f"Open http://127.0.0.1:{args.port} on the VM, or forward that port over SSH.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"Dashboard install failed: {error}", file=sys.stderr)
        sys.exit(1)
