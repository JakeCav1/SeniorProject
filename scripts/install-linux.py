"""Install a locally built Linux binary for the current user; never start services."""
import argparse
import os
from pathlib import Path
import subprocess
import sys
import tempfile


def absolute(value):
    path = Path(value).expanduser()
    if not path.is_absolute():
        raise ValueError(f"Expected an absolute path: {path}")
    if any(ord(c) < 32 or ord(c) == 127 for c in str(path)):
        raise ValueError("Paths must not contain control characters")
    return path


def unit_path(value):
    # Quoted absolute paths support spaces. Reject systemd expansion/escape syntax.
    if any(c in str(value) for c in '\\"$%'):
        raise ValueError('Service paths cannot contain backslash, quote, dollar, or percent characters')
    return f'"{value}"'


def atomic_write(path, data, mode):
    path.parent.mkdir(parents=True, exist_ok=True)
    name = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".chomp-install-", delete=False) as output:
            name = output.name
            output.write(data)
            output.flush()
            os.fchmod(output.fileno(), mode)
            os.fsync(output.fileno())
        os.replace(name, path)
        name = None
    finally:
        if name is not None:
            os.unlink(name)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=Path(__file__).resolve().parents[1] / "target/release/chompedr")
    parser.add_argument("--prefix", default=str(Path.home() / ".local"), help="Absolute installation prefix; executable goes in bin/")
    parser.add_argument("--service", action="store_true", help="Write an optional systemd user unit, without enabling or starting it")
    parser.add_argument("--replace", action="store_true", help="Replace existing executable/unit; stop any running monitor first")
    args = parser.parse_args()
    if sys.platform != "linux":
        parser.error("This installer requires Linux")
    if os.geteuid() == 0:
        parser.error("Run as your regular user, without sudo")
    prefix = absolute(args.prefix)
    source = args.binary.resolve(strict=True)
    if not source.is_file() or not os.access(source, os.X_OK):
        raise ValueError("Build an executable with cargo build --release --locked first")
    version = subprocess.run([str(source), "--version"], check=True, capture_output=True, text=True, timeout=10).stdout.strip()
    if not version.startswith("chompedr "):
        raise ValueError("The supplied binary does not identify itself as chompedr")
    destinations = [(prefix / "bin/chompedr", source.read_bytes(), 0o755)]
    if args.service:
        config = absolute(os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config"))
        state = absolute(os.environ.get("XDG_STATE_HOME") or str(Path.home() / ".local/state")) / "chomp-edr/ssh"
        executable = unit_path(destinations[0][0])
        checkpoint = unit_path(state)
        unit = f"""# Generated by Chomp EDR install-linux.py
[Unit]
Description=Chomp EDR SSH journal monitor

[Service]
Type=simple
ExecStart={executable} monitor --checkpoint {checkpoint}
Restart=no
KillMode=control-group
TimeoutStopSec=15
UMask=0077
NoNewPrivileges=yes
StandardOutput=journal
StandardError=journal

[Install]
WantedBy=default.target
"""
        destinations.append((config / "systemd/user/chompedr.service", unit.encode(), 0o644))
    # Validate every destination before modifying either file.
    for path, _, _ in destinations:
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError(f"Refusing to replace nonregular destination: {path}")
        if path.exists() and not args.replace:
            raise ValueError(f"Already exists: {path}; stop monitoring and use --replace to upgrade")
        if path == source:
            raise ValueError("Source binary and installation destination must differ")
    for path, data, mode in destinations:
        atomic_write(path, data, mode)
        print(f"Installed {path}")
    print(f"{version}. Add {prefix / 'bin'} to your PATH if needed.")
    if args.service:
        print("Service written but NOT enabled or started. After checking journal access:")
        print("  systemctl --user daemon-reload")
        print("  systemctl --user start chompedr.service")
        print("  systemctl --user status chompedr.service")
        print("Optional login startup: systemctl --user enable chompedr.service")
    else:
        print("Run chompedr monitor in your Linux terminal to begin.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        print(f"Install failed: {error}", file=sys.stderr)
        sys.exit(1)
